#!/usr/bin/env bash
# upwork-cron Linux uninstaller (per-user).
#
# Stops the watcher, removes the cron entry and the upcron commands, preserves
# the data directory by default, then removes the installed app.
#
# Usage: ./uninstall.sh [--purge-data]

set -euo pipefail

APP_NAME="upwork-cron"
PURGE=0

usage() {
  cat <<EOF
Usage: $0 [options]

Options:
  --purge-data   Remove saved tokens, database, and logs instead of preserving
                 them in a backup directory.
  -h, --help     Show this help.
EOF
}

say() { printf '\n==> %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die() {
  printf '\nERROR: %s\n' "$*" >&2
  printf 'Uninstall did not complete.\n' >&2
  exit 1
}

on_cancel() {
  printf '\nUninstall cancelled.\n' >&2
  printf 'Run the uninstaller again to finish.\n' >&2
  exit 130
}
trap on_cancel INT TERM

while [ "$#" -gt 0 ]; do
  case "$1" in
    --purge-data) PURGE=1 ;;
    -h|--help)
      usage
      exit 0
      ;;
    *) die "Unknown option: $1 (see --help)." ;;
  esac
  shift
done

[ "$(uname -s 2>/dev/null || true)" = "Linux" ] || die 'This uninstaller is for Linux.'
if [ -z "${HOME:-}" ] || [ ! -d "$HOME" ]; then
  die 'HOME is not set to a valid directory.'
fi
# Run from HOME, not a source checkout: `python -m` imports from the current
# directory first, and this also keeps the cwd outside the tree we delete.
cd "$HOME"

XDG_DATA="${XDG_DATA_HOME:-$HOME/.local/share}"
INSTALL_ROOT="$XDG_DATA/$APP_NAME"
APP_DIR="$INSTALL_ROOT/app"
VENV_DIR="$INSTALL_ROOT/venv"
DATA_DIR="$INSTALL_ROOT/data"
BIN_DIR="$HOME/.local/bin"
PROFILE="$HOME/.profile"
BACKUP="$INSTALL_ROOT-data-backup"

say "Stopping watcher and removing schedule"
if [ -x "$VENV_DIR/bin/python" ]; then
  set +e
  UPWORK_CRON_DATA="$DATA_DIR" "$VENV_DIR/bin/python" -m upwork_cron stop
  rc=$?
  set -e
  if [ "$rc" -eq 130 ]; then on_cancel; fi
  if [ "$rc" -ne 0 ]; then
    warn 'stop command failed (continuing with manual cleanup).'
  fi
elif [ ! -d "$INSTALL_ROOT" ]; then
  warn "upwork-cron does not appear to be installed at $INSTALL_ROOT."
fi

# Always remove the cron entry, even if the stop command failed.
if command -v crontab >/dev/null 2>&1; then
  current="$(crontab -l 2>/dev/null || true)"
  if [ -n "$current" ] && printf '%s\n' "$current" | grep -Fq "$APP_DIR/run.sh"; then
    filtered="$(printf '%s\n' "$current" | grep -Fv "$APP_DIR/run.sh" || true)"
    if [ -n "$filtered" ]; then
      printf '%s\n' "$filtered" | crontab - || warn 'Could not rewrite the crontab.'
    else
      crontab -r || warn 'Could not remove the crontab.'
    fi
  fi
fi

# Stop only the PID recorded by the watcher, and only if it is still ours.
pid_file="$DATA_DIR/watcher.pid"
if [ -f "$pid_file" ]; then
  pid="$(head -n 1 "$pid_file" 2>/dev/null | tr -cd '0-9' || true)"
  if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
    cmdline="$(ps -p "$pid" -o args= 2>/dev/null || true)"
    if [[ "$cmdline" == *upwork_cron* ]]; then
      kill "$pid" 2>/dev/null || true
      for _ in {1..30}; do
        kill -0 "$pid" 2>/dev/null || break
        sleep 0.1
      done
      kill -9 "$pid" 2>/dev/null || true
    fi
  fi
fi

say "Removing upcron from your PATH"
if [ -f "$PROFILE" ] && grep -qF '# >>> upwork-cron installer >>>' "$PROFILE"; then
  if sed -i '/# >>> upwork-cron installer >>>/,/# <<< upwork-cron installer <<</d' "$PROFILE"; then
    printf 'Removed the PATH entry from %s.\n' "$PROFILE"
  else
    warn "Could not edit $PROFILE; remove the upwork-cron PATH block manually."
  fi
fi

remove_shim() {
  local target="$1"
  if [ -L "$target" ]; then
    local link
    link="$(readlink "$target" 2>/dev/null || true)"
    case "$link" in
      upcron|"$BIN_DIR/upcron"|"$INSTALL_ROOT"/*) rm -f "$target" ;;
    esac
  elif [ -f "$target" ] && grep -qF 'Generated by the upwork-cron Linux installer' "$target" 2>/dev/null; then
    rm -f "$target"
  fi
}
remove_shim "$BIN_DIR/upcron"
remove_shim "$BIN_DIR/upwork-cron"

if [ "$PURGE" -eq 1 ]; then
  rm -rf "$BACKUP"
elif [ -d "$DATA_DIR" ]; then
  say "Preserving data"
  rm -rf "$BACKUP"
  if cp -a "$DATA_DIR" "$BACKUP"; then
    printf 'Data preserved at %s (token, db, logs).\n' "$BACKUP"
    printf 'Run with --purge-data to remove everything.\n'
  else
    die "Could not preserve data. $INSTALL_ROOT was left in place."
  fi
fi

say "Removing installed files"
if [ -d "$INSTALL_ROOT" ]; then
  rm -rf "$INSTALL_ROOT" || die "Could not remove $INSTALL_ROOT."
fi

say "Uninstall complete"
if [ "$PURGE" -eq 1 ]; then
  printf 'All app files and data removed.\n'
else
  printf 'App removed. Saved data: %s\n' "$BACKUP"
fi
